"""Per-field citation audit of the current extraction (RAG-first).

Writes the citation-audit section of docs/RESULTS.md: one row per extracted field with its citation
status, page and clause, so every headline provenance number can be traced
to the field it counts.

    python -m qa.citation_audit            # from backend/
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "extracted" / "extracted.json"
OUT = ROOT.parent / "docs" / "RESULTS.md"
START, END = "<!-- citations:start -->", "<!-- citations:end -->"

STATUS_LABEL = {
    "verified": "verified - quote matched in the stored clause text",
    "transcribed": "transcribed - quote matched in Gemini's transcription of a scanned page",
    "unverified": "offered, but the quote did not match the cited clause - withheld from reports",
    "missing": "no citation offered",
    "none": "no citation offered",
}
UNCITED = ("none", "missing")


def audit(data: dict) -> tuple[list[tuple], Counter]:
    rows, counts = [], Counter()
    for treaty_id in sorted(data["extracted"]):
        provenance = data["provenance"].get(treaty_id, {})
        for field in sorted(data["extracted"][treaty_id]):
            cite = provenance.get(field) or {}
            status = cite.get("status") or "none"
            counts[status] += 1
            rows.append((treaty_id, field, status, cite.get("page"), cite.get("clause_no"),
                         cite.get("reason")))
    return rows, counts


def render(rows: list[tuple], counts: Counter, model: str | None) -> str:
    total = sum(counts.values())
    offered = total - sum(counts.get(s, 0) for s in UNCITED)
    checked = counts.get("verified", 0) + counts.get("transcribed", 0)
    lines = [
        "## 3. Citation audit - every extracted field",
        "",
        "Generated by `backend/qa/citation_audit.py` from `backend/data/extracted/extracted.json` "
        f"(RAG-first pipeline{f', {model}' if model else ''}). One row per extracted field.",
        "",
        f"**Coverage: {offered}/{total} fields carry a citation. Of those, {checked}/{offered} "
        "check out against the page** (verified or transcribed). A citation that does not check out "
        "is never shown as a finding.",
        "",
        "This replaces the 77.4% coverage measured on the earlier whole-document extractor "
        "(section 5), which is no longer in use.",
        "",
        "| Status | Fields | Meaning |",
        "|---|---|---|",
    ]
    for status, n in counts.most_common():
        lines.append(f"| `{status}` | {n} | {STATUS_LABEL.get(status, 'not checkable - see the reason column')} |")
    lines += ["", "<details><summary>All fields</summary>", "", "| Treaty | Field | Status | Page | Clause | Reason if not verified |", "|---|---|---|---|---|---|"]
    for treaty_id, field, status, page, clause, reason in rows:
        lines.append(f"| {treaty_id} | `{field}` | {status} | {page or '-'} | {clause or '-'} | "
                     f"{(reason or '').replace('|', '/')} |")
    lines += ["", "</details>"]
    return "\n".join(lines) + "\n"


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows, counts = audit(data)
    doc = OUT.read_text(encoding="utf-8")
    head, _, rest = doc.partition(START)
    _, _, tail = rest.partition(END)
    OUT.write_text(f"{head}{START}\n{render(rows, counts, data.get('model'))}{END}{tail}", encoding="utf-8")
    print(f"{OUT}: {sum(counts.values())} fields, {dict(counts)}")


if __name__ == "__main__":
    main()
